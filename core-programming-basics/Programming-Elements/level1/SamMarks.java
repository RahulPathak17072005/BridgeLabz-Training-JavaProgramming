public class SamMarks {
    public static void main(String[] args) {
        int mathMarks = 85; // Sam's math marks
        int scienceMarks = 90; // Sam's science marks
        int englishMarks = 78; // Sam's English marks
        int totalMarks = mathMarks + scienceMarks + englishMarks; // Calculate total marks
        double averageMarks = totalMarks / 3.0; // Calculate average marks
        System.out.println("Sam's total marks: " + totalMarks);
        System.out.println("Sam's average marks: " + averageMarks);
    }
}